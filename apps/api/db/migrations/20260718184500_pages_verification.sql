CREATE TABLE page_verification_types (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  verification_type VARCHAR(50) UNIQUE NOT NULL,
  verification_title VARCHAR(100) NOT NULL,
  verification_description VARCHAR(255),
  is_admin_assignable BOOLEAN DEFAULT FALSE NOT NULL,
  for_who VARCHAR(50) NOT NULL
);

CREATE TABLE pages_verified (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_type VARCHAR(50) NOT NULL,
  page_id BIGINT NOT NULL,
  verification_type_id SMALLINT NOT NULL REFERENCES page_verification_types(id) ON DELETE CASCADE,
  verified_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UNIQUE(page_type, page_id, verification_type_id)
);

CREATE INDEX idx_pages_verified_page_type ON pages_verified(page_type);
CREATE INDEX idx_pages_verified_page_id ON pages_verified(page_id);
CREATE INDEX idx_pages_verified_verification_type_id ON pages_verified(verification_type_id);


