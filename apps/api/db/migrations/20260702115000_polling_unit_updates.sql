-- Polling unit status categories (lifecycle stages of a polling unit)
CREATE TABLE IF NOT EXISTS polling_unit_status_categories (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  slug VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255),
  color VARCHAR(30) DEFAULT 'slate',
  sort_order SMALLINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Options for each polling unit status category
CREATE TABLE IF NOT EXISTS polling_unit_status_options (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status_category_id SMALLINT REFERENCES polling_unit_status_categories(id) ON DELETE CASCADE NOT NULL,
  name VARCHAR(255) NOT NULL,
  sort_order SMALLINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- High-level issue categories (e.g. Violence, Technical / BVAS, Logistics, Malpractice)
CREATE TABLE IF NOT EXISTS polling_unit_issue_categories (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  slug VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255),
  color VARCHAR(30) DEFAULT 'amber',
  sort_order SMALLINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Detailed issue options under each category (specific offenses / violations)
CREATE TABLE IF NOT EXISTS polling_unit_issue_options (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_category_id SMALLINT REFERENCES polling_unit_issue_categories(id) ON DELETE CASCADE NOT NULL,
  name VARCHAR(255) NOT NULL,
  severity VARCHAR(20) DEFAULT 'medium', -- 'low', 'medium', 'high', 'critical'
  sort_order SMALLINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Primary polling unit updates table
CREATE TABLE IF NOT EXISTS polling_unit_updates (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  
  -- The core relationship linking the update to the agent's assignment
  assignment_id BIGINT REFERENCES polling_unit_assignments(id) ON DELETE SET NULL,
  
  -- Denormalized references for fast dashboard filtering
  election_group_id INT REFERENCES election_groups(id) ON DELETE CASCADE NOT NULL,
  party_id SMALLINT REFERENCES parties(id) ON DELETE SET NULL,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  state_id SMALLINT REFERENCES c_states(id) ON DELETE SET NULL,
  lga_id INT REFERENCES lgas(id) ON DELETE SET NULL,
  ward_id INT REFERENCES wards(id) ON DELETE SET NULL,
  senatorial_district_id INT REFERENCES senatorial_districts(id) ON DELETE SET NULL,
  federal_constituency_id INT REFERENCES federal_constituencies(id) ON DELETE SET NULL,
  state_assembly_constituency_id INT REFERENCES state_constituencies(id) ON DELETE SET NULL,
  polling_unit_id INTEGER REFERENCES polling_units(id) ON DELETE CASCADE NOT NULL,
  
  -- Status category and option classification
  status_category_id SMALLINT REFERENCES polling_unit_status_categories(id) ON DELETE SET NULL,
  status_option_id SMALLINT REFERENCES polling_unit_status_options(id) ON DELETE SET NULL,
  
  -- Ongoing issues flag
  has_issues BOOLEAN DEFAULT FALSE,
  
  -- Update details
  title VARCHAR(255),
  message TEXT NOT NULL,
  has_media BOOLEAN NOT NULL DEFAULT FALSE,
  
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Stateful polling unit issues (tracks active issues, start/end downtime, resolution)
CREATE TABLE IF NOT EXISTS polling_unit_with_issues (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  update_id BIGINT REFERENCES polling_unit_updates(id) ON DELETE SET NULL,
  election_group_id INT REFERENCES election_groups(id) ON DELETE CASCADE NOT NULL,
  party_id SMALLINT REFERENCES parties(id) ON DELETE SET NULL,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  assignment_id BIGINT REFERENCES polling_unit_assignments(id) ON DELETE SET NULL,
  polling_unit_id INTEGER REFERENCES polling_units(id) ON DELETE CASCADE NOT NULL,
  
  issue_category_id SMALLINT REFERENCES polling_unit_issue_categories(id) ON DELETE RESTRICT NOT NULL,
  issue_option_id SMALLINT REFERENCES polling_unit_issue_options(id) ON DELETE RESTRICT NOT NULL,
  
  is_active BOOLEAN DEFAULT TRUE NOT NULL,
  time_issue_started TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  time_issue_ended TIMESTAMPTZ,
  
  resolution_notes TEXT
);

-- Child table for media attachments (photos, videos, audio/voice notes)
CREATE TABLE IF NOT EXISTS polling_unit_update_media (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  update_id BIGINT NOT NULL REFERENCES polling_unit_updates(id) ON DELETE CASCADE,
  media_type VARCHAR(20) NOT NULL CHECK (media_type IN ('image', 'video', 'audio')),
  url VARCHAR(2000) NOT NULL,
  thumbnail_url VARCHAR(2000),
  duration_seconds INT,
  file_size_bytes BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_pu_update_media_update ON polling_unit_update_media(update_id);

